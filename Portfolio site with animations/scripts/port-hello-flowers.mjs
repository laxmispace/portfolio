// Rebuilds the loader character from src/assets/loader/Hello With Flowers.html:
// copies its soft rig into helloFlowersRig.ts and its drawing (layers, smile, viewBox)
// into helloFlowersData.ts. Run after editing the HTML file:
//   node scripts/port-hello-flowers.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "src/assets/loader/Hello With Flowers.html";
const OUT = "src/app/components/walker";
const html = readFileSync(SRC, "utf8");

const rigStart = html.indexOf("const RIG=(function(){");
const rigEnd = html.indexOf("if(typeof module");
if (rigStart < 0 || rigEnd < 0) throw new Error("couldn't find the RIG in " + SRC);
const rig = html.slice(rigStart, rigEnd).trim().replace("const RIG=(function(){", "export const RIG=(function(){");

const data = html.match(/const layers=(\[[\s\S]*?\]), SM=(\{[\s\S]*?\});\n/);
if (!data) throw new Error("couldn't find the layers in " + SRC);
const layers = JSON.parse(data[1]);
const smile = JSON.parse(data[2]);
const [x, y, w, h] = html.match(/<svg id="scene" viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);

writeFileSync(
  `${OUT}/helloFlowersRig.ts`,
  `// @ts-nocheck - generated by scripts/port-hello-flowers.mjs from ${SRC}; edit that file, not this.
// Soft rig: every outline point is moved by a smooth field, so the drawing bends instead of
// being cut apart - the hand waves, the flowers sway, the eyes blink.
${rig}
`,
);
writeFileSync(
  `${OUT}/helloFlowersData.ts`,
  `// The "Hello With Flowers" drawing: each layer's outline as path commands (c) and points (p),
// flattened x,y pairs. Generated by scripts/port-hello-flowers.mjs from ${SRC}.
export type RigLayer = { f: string; eo: boolean; tag: string; c: string; p: number[] };
export const HELLO_VIEWBOX = { x: ${x}, y: ${y}, w: ${w}, h: ${h} };
export const HELLO_LAYERS: RigLayer[] = ${JSON.stringify(layers)};
export const HELLO_SMILE: { small: number[][]; full: number[][] } = ${JSON.stringify(smile)};
`,
);
console.log(`ported ${layers.length} layers, viewBox ${x} ${y} ${w} ${h}`);
